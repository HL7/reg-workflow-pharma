#!/usr/bin/env python3
"""Generate RWI-pharma capability artifacts.

Inputs
  capabilities/capabilities.yaml             decisions: actors, interactions, searches, expectations, requirements
  fsh-generated/resources/StructureDefinition-*.json   profiles (Must Support elements), from the last SUSHI run

Outputs (overwritten on every run - edit the YAML, not these files)
  input/fsh/Capabilities.generated.fsh            ActorDefinitions, CapabilityStatements, SearchParameters
  input/pagecontent/capability-requirements.md    conformance statements (IG Publisher § markup)

Usage: python3 scripts/gen_capabilities.py   (run from the IG root, after SUSHI has run at least once)
"""
import json, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = os.path.join(ROOT, "capabilities", "capabilities.yaml")
SD_DIR = os.path.join(ROOT, "fsh-generated", "resources")
OUT_FSH = os.path.join(ROOT, "input", "fsh", "Capabilities.generated.fsh")
OUT_MD = os.path.join(ROOT, "input", "pagecontent", "capability-requirements.md")
EXP = "http://hl7.org/fhir/StructureDefinition/capabilitystatement-expectation"
NL = "\r\n"
SHORT = {"rwipharma-server": "srv", "rwipharma-applicant-client": "app", "rwipharma-regulator-client": "reg",
         "rwipharma-notification-receiver": "rcv"}
MS_TEXT = {"store": "storing and returning", "populate": "populating", "process": "processing",
           "populate-process": "populating and processing"}

def die(msg):
    sys.exit("gen_capabilities: " + msg)

def q(s):
    """FSH string literal."""
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)

cfg = yaml.safe_load(open(CFG, encoding="utf-8"))
canon = cfg["meta"]["canonical"]; date = cfg["meta"]["date"]
actors = {a["id"]: a for a in cfg["actors"]}

# ---- profiles: name, title, url, Must Support elements ----
profiles = {}
for f in sorted(os.listdir(SD_DIR)) if os.path.isdir(SD_DIR) else []:
    if not (f.startswith("StructureDefinition-") and f.endswith(".json")):
        continue
    sd = json.load(open(os.path.join(SD_DIR, f), encoding="utf-8"))
    if sd.get("derivation") != "constraint":
        continue
    ms = [e["id"] for e in sd.get("differential", {}).get("element", [])
          if e.get("mustSupport") and "." in e.get("id", "")]
    profiles[sd["id"]] = {"name": sd["name"], "title": sd.get("title") or sd["name"], "url": sd["url"],
                          "type": sd["type"], "ms": ms}
used = {p for cs in cfg["capabilities"].values() for r in cs["resources"] for p in r.get("profiles", [])}
used |= {p for items in (cfg.get("mustSupportOnly") or {}).values() for r in items for p in r.get("profiles", [])}
missing = sorted(used - set(profiles))
if missing:
    die(f"profiles not found in {SD_DIR}: {missing}. Run SUSHI first, or fix the profile ids in the YAML.")

# ---- FSH ----
L = ["// GENERATED by scripts/gen_capabilities.py from capabilities/capabilities.yaml - do not edit by hand.", ""]

def exp(prefix, value):
    L.append(f'* {prefix}.extension[0].url = "{EXP}"')
    L.append(f"* {prefix}.extension[0].valueCode = #{value}")

for a in cfg["actors"]:
    L += [f"Instance: {a['name']}Actor", "InstanceOf: ActorDefinition", "Usage: #definition",
          f"Title: {q(a['title'])}", f"Description: {q(a['description'])}",
          f'* id = "{a["id"]}"', f'* url = "{canon}/ActorDefinition/{a["id"]}"', f"* name = {q(a['name'])}",
          f"* title = {q(a['title'])}", "* status = #active", "* experimental = false", f'* date = "{date}"',
          "* type = #system", f"* description = {q(a['description'])}"]
    if a.get("cs"):
        L.append(f'* capabilities = "{canon}/CapabilityStatement/{a["cs"]["id"]}"')
    L.append("")

for sp in cfg.get("customSearchParameters", []):
    L += [f"Instance: {pascal(sp['id'])}SearchParameter", "InstanceOf: SearchParameter", "Usage: #definition",
          f"Title: {q(sp['title'])}", f"Description: {q(sp['description'])}",
          f'* id = "{sp["id"]}"', f'* url = "{canon}/SearchParameter/{sp["id"]}"', f"* name = {q(sp['name'])}",
          f"* title = {q(sp['title'])}", "* status = #active", "* experimental = false", f'* date = "{date}"',
          f"* description = {q(sp['description'])}", f"* code = #{sp['code']}", f"* base = #{sp['base']}",
          f"* type = #{sp['type']}", f"* expression = {q(sp['expression'])}", "* processingMode = #normal", ""]

registry = cfg["searchParams"]; ops = cfg["operations"]
for aid, cs in cfg["capabilities"].items():
    a = actors[aid]; mode = a["cs"]["mode"]; csid = a["cs"]["id"]
    title = f"{a['title']} CapabilityStatement"
    desc = f"Expected capabilities of the {a['title']} actor ({mode}) in RWI-pharma regulatory workflows."
    L += [f"Instance: {a['name']}CapabilityStatement", "InstanceOf: CapabilityStatement", "Usage: #definition",
          f"Title: {q(title)}", f"Description: {q(desc)}",
          f'* id = "{csid}"', f'* url = "{canon}/CapabilityStatement/{csid}"', f"* name = {q(a['name'] + 'CapabilityStatement')}",
          f"* title = {q(title)}", "* status = #active", "* experimental = false", f'* date = "{date}"',
          f"* description = {q(desc)}", "* kind = #requirements", f"* fhirVersion = #{cfg['meta']['fhirVersion']}",
          "* format[0] = #json", "* format[1] = #xml",
          f"* rest[0].mode = #{mode}", f"* rest[0].documentation = {q(cs['documentation'])}",
          '* rest[0].security.service.text = "SMART-on-FHIR (SMART Backend Services)"',
          f"* rest[0].security.description = {q(cs['security'])}"]
    for ri, r in enumerate(cs["resources"]):
        p = f"rest[0].resource[{ri}]"
        L.append(f"* {p}.type = #{r['type']}")
        exp(p, r["expectation"])
        for pi, pid in enumerate(r.get("profiles", [])):
            L.append(f'* {p}.supportedProfile[{pi}] = "{profiles[pid]["url"]}"')
        doc = r.get("documentation", "")
        if r.get("ms"):
            for pid in r.get("profiles", []):
                ms = profiles[pid]["ms"]
                if ms:
                    doc += (" " if doc else "") + (f"Must Support ({profiles[pid]['title']}): the {a['title']} SHALL be capable of "
                            f"{MS_TEXT[r['ms']]} " + ", ".join(ms) + ".")
        if doc:
            L.append(f"* {p}.documentation = {q(doc)}")
        for ii, (code, e) in enumerate(r.get("interactions", {}).items()):
            L.append(f"* {p}.interaction[{ii}].code = #{code}"); exp(f"{p}.interaction[{ii}]", e)
        for k in ("versioning", "conditionalDelete"):
            if k in r: L.append(f"* {p}.{k} = #{r[k]}")
        for k in ("readHistory", "updateCreate", "conditionalCreate", "conditionalUpdate"):
            if k in r: L.append(f"* {p}.{k} = {str(r[k]).lower()}")
        for k in ("searchInclude", "searchRevInclude"):
            for xi, v in enumerate(r.get(k, [])):
                L.append(f"* {p}.{k}[{xi}] = {q(v)}")
        for si, (code, e) in enumerate(r.get("search", {}).items()):
            spd = registry.get(r["type"], {}).get(code) or die(f"search param {r['type']}.{code} not in registry")
            s = f"{p}.searchParam[{si}]"
            L += [f"* {s}.name = {q(code)}", f'* {s}.definition = "{spd["def"]}"', f"* {s}.type = #{spd['type']}"]
            if spd.get("doc"): L.append(f"* {s}.documentation = {q(spd['doc'])}")
            exp(s, e)
        for oi, (name, e) in enumerate(r.get("operations", {}).items()):
            o = f"{p}.operation[{oi}]"
            L += [f"* {o}.name = {q(name)}", f'* {o}.definition = "{ops[name]["def"]}"']; exp(o, e)
    for ii, (code, e) in enumerate(cs.get("interactions", {}).items()):
        L.append(f"* rest[0].interaction[{ii}].code = #{code}"); exp(f"rest[0].interaction[{ii}]", e)
    L.append("")

# ---- requirements page ----
def actor_links(ids):
    return ", ".join(f"[{actors[i]['title']}](ActorDefinition-{i}.html)" for i in ids)

M = ["<!-- GENERATED by scripts/gen_capabilities.py from capabilities/capabilities.yaml - do not edit by hand. -->", "",
     "This page lists the capability requirements for systems that implement RWI-pharma. They complement the "
     "computable requirements in the [CapabilityStatements](#actors) and profiles, and cover behaviour that no profile "
     "can express: how Task versions work, which searches the workflow depends on, how documents and notifications "
     "are exchanged, and who may change what.", "",
     "Each statement has an id that links to it, and applies to the actors listed. The table at the end lists every "
     "conformance statement in this guide and can be filtered by actor. Reading the table alone is not enough to "
     "implement the guide: it does not include the requirements expressed in profiles and CapabilityStatements, and "
     "each statement is easier to understand in its context on this page.", "",
     "### Actors {#actors}", "", "| Actor | Role | CapabilityStatement |", "|---|---|---|"]
for a in cfg["actors"]:
    cs = f"[{a['title']}](CapabilityStatement-{a['cs']['id']}.html)" if a.get("cs") else "none (not a FHIR server)"
    M.append(f"| [{a['title']}](ActorDefinition-{a['id']}.html) | {a['description']} | {cs} |")
M.append("")
ids = set()
for sec in cfg["requirements"]:
    M += [f"### {sec['section']}", ""]
    for it in sec["items"]:
        assert it["id"] not in ids, it["id"]; ids.add(it["id"])
        for x in it["actors"]: assert x in actors, x
        M += [f"§{it['id']}^{','.join(it['actors'])}:{it['text']}§", ""]
        if it.get("basis"): M += [f"<span style=\"font-size:.85em;color:#555;\">Basis: {it['basis']}</span>", ""]
M += ["### Must Support", "",
      "Must Support elements are marked in each profile. For each actor, *populating* means the system can supply the "
      "element when it has the data, *processing* means it can read the element and act on it, and *storing and "
      "returning* means the server keeps the element and returns it unchanged. These statements are derived from the "
      "profiles.", ""]
for aid, cs in cfg["capabilities"].items():
    a = actors[aid]
    for r in cs["resources"]:
        if not r.get("ms"): continue
        for pid in r.get("profiles", []):
            ms = profiles[pid]["ms"]
            if not ms: continue
            sid = f"ms-{SHORT[aid]}-{pid}"[:64]
            assert sid not in ids, sid; ids.add(sid)
            els = ", ".join(f"`{m}`" for m in ms)
            M += [f"§{sid}^{aid}:The {a['title']} **SHALL** be capable of {MS_TEXT[r['ms']]} the Must Support elements "
                  f"of the [{profiles[pid]['title']}](StructureDefinition-{pid}.html) profile: {els}.§", ""]
for aid, items in (cfg.get("mustSupportOnly") or {}).items():
    a = actors[aid]
    for r in items:
        for pid in r.get("profiles", []):
            ms = profiles[pid]["ms"]
            if not ms: continue
            sid = f"ms-{SHORT[aid]}-{pid}"[:64]
            assert sid not in ids, sid; ids.add(sid)
            els = ", ".join(f"`{m}`" for m in ms)
            M += [f"§{sid}^{aid}:The {a['title']} **SHALL** be capable of {MS_TEXT[r['ms']]} the Must Support elements "
                  f"of the [{profiles[pid]['title']}](StructureDefinition-{pid}.html) profile: {els}.§", ""]
M += ["### All conformance statements", "", "§§§", ""]

for path, lines in ((OUT_FSH, L), (OUT_MD, M)):
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(NL.join(lines))
print(f"wrote {os.path.relpath(OUT_FSH, ROOT)} ({sum(1 for x in L if x.startswith('Instance:'))} instances)")
print(f"wrote {os.path.relpath(OUT_MD, ROOT)} ({len(ids)} conformance statements)")
